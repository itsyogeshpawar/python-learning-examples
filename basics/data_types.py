# Data Types in Python
# Python supports several built-in data types.

integer_num = 10           # int
float_num = 3.14           # float
string_text = "Hello"      # str
boolean_val = True         # bool
list_example = [1, 2, 3]   # list
tuple_example = (4, 5, 6)  # tuple
dict_example = {"a": 1}   # dict

print(type(integer_num))
print(type(float_num))
print(type(string_text))
print(type(boolean_val))
print(type(list_example))
print(type(tuple_example))
print(type(dict_example))

# Explanation:
# - Use type() to check the data type of a variable.
# - Python is dynamically typed, so you don't need to declare types explicitly.
